// Turns brand/festive/*.svg into src/theme/festiveArt.ts. Run after changing the artwork:
//   node scripts/build-festive-art.js
const fs = require('fs');
const path = require('path');

const art = path.join(__dirname, '../../brand/festive');
const ids = fs.readdirSync(art)
  .filter(file => file.startsWith('top-'))
  .map(file => file.slice('top-'.length, -'.svg'.length))
  .sort();
const read = file => JSON.stringify(fs.readFileSync(path.join(art, file), 'utf8').trim());
const rows = ids.map(id => `  ${id}: {top: ${read(`top-${id}.svg`)}, scene: ${read(`scene-${id}.svg`)}},`);

fs.writeFileSync(
  path.join(__dirname, '../src/theme/festiveArt.ts'),
  `// Generated by scripts/build-festive-art.js from brand/festive. Don't edit by hand.\nexport const FESTIVE_ART = {\n${rows.join('\n')}\n};\n`,
);
